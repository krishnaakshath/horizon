/**
 * Reference matrices generated with segno (level M, byte mode, fixed mask, no micro codes). The
 * texts fill their version exactly, so no pad bytes follow the terminator (segno pads differently
 * there, which decoders ignore).
 */
class QrCodeTest {
    private fun rows(q: QrCode) = q.modules.joinToString("|") { r -> r.joinToString("") { if (it) "1" else "0" } }

    /** Compares cell by cell so a failure names the first wrong modules. */
    private fun same(expected: String, q: QrCode) {
        val e = expected.split("|")
        val diffs = ArrayList<String>()
        for (y in e.indices) for (x in e[y].indices) if ((e[y][x] == '1') != q[x, y]) diffs += "($x,$y)"
        assertEquals(diffs.take(40).joinToString(" ") + " of ${diffs.size}", 0, diffs.size)
    }

    @Test fun hello_version1_mask4_matchesReference() {
        val q = QrCode.encode("HELLO WORLD 12", forceMask = 4)!!
        assertEquals(1, q.version)
        same(V1, q)
    }

    @Test fun pairingUrl_version3_mask2_matchesReference() {
        val q = QrCode.encode("http://192.168.1.20:8765/#pair=123456&x=ab", forceMask = 2)!!
        assertEquals(3, q.version)
        same(V3, q)
    }

    @Test fun longText_version7_withVersionBits_matchesReference() {
        val q = QrCode.encode("x".repeat(152), forceMask = 5)!!
        assertEquals(V7_SIZE, q.size)
        same(V7, q)
    }

    @Test fun finderPatterns_inThreeCorners() {
        val q = QrCode.encode("http://10.0.0.5:8765/#pair=000000")!!
        val n = q.size
        for ((ox, oy) in listOf(0 to 0, n - 7 to 0, 0 to n - 7)) {
            for (d in 0..6) {
                assertTrue(q[ox + d, oy]); assertTrue(q[ox + d, oy + 6]); assertTrue(q[ox, oy + d]); assertTrue(q[ox + 6, oy + d])
            }
            for (d in 1..5) assertEquals(false, q[ox + d, oy + 1])
            for (y in 2..4) for (x in 2..4) assertTrue(q[ox + x, oy + y])
        }
    }

    @Test fun formatBits_knownValues() {
        // Level M: mask 0 -> 101010000010010, mask 4 -> 100010111111001 (ISO 18004 table C.1).
        assertEquals(0b101010000010010, QrCode.formatBits(0))
        assertEquals(0b100010111111001, QrCode.formatBits(4))
        assertEquals(0x07C94, QrCode.versionBits(7))
    }

    @Test fun reedSolomon_gfMultiply() {
        assertEquals(0, QrCode.gfMul(0, 7))
        assertEquals(0x1D, QrCode.gfMul(0x80, 2))
    }

    @Test fun capacity_andTooLong() {
        assertEquals(14, QrCode.byteCapacity(1))
        assertEquals(213, QrCode.byteCapacity(10))
        assertNotNull(QrCode.encode("a".repeat(213)))
        assertNull(QrCode.encode("a".repeat(214)))
    }

    @Test fun autoMask_pairingUrlFitsSmallVersion() {
        val q = QrCode.encode("http://192.168.100.200:8765/#pair=987654")!!
        assertTrue(q.version <= 4)
    }

